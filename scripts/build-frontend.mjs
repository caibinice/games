import { build as viteBuild } from 'vite';
import vue from '@vitejs/plugin-vue';
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync } from 'node:fs';
import { resolve, join, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const files = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? files(join(dir, e.name)) : [join(dir, e.name)]));
export function sourceHash() {
  const h = createHash('sha256');
  const native = ['tank', 'contra', 'racer', 'lianliankan', 'paopaotang'].flatMap((id) =>
    files(join(ROOT, 'games', id, 'public')).filter(
      (p) => p.endsWith('.mjs') && !p.endsWith('app.mjs') && !p.endsWith('runtime.mjs'),
    ),
  );
  for (const p of [
    ...files(join(ROOT, 'web')).filter((p) => !p.endsWith('build-manifest.json')),
    ...native,
    join(ROOT, 'package-lock.json'),
    join(ROOT, 'scripts/build-frontend.mjs'),
    join(ROOT, 'games/tank/public/assets/battle-city-license.html'),
  ].sort()) {
    h.update(relative(ROOT, p).replaceAll('\\', '/'));
    h.update(readFileSync(p, 'utf8').replaceAll('\r\n', '\n'));
  }
  return h.digest('hex');
}
export async function buildFrontend() {
  const result = await viteBuild({
    configFile: false,
    root: join(ROOT, 'web'),
    base: '/games/ui/',
    plugins: [vue({ template: { transformAssetUrls: { tags: {}, includeAbsolute: false } } })],
    logLevel: 'warn',
    build: {
      write: false,
      cssCodeSplit: true,
      target: 'es2022',
      rollupOptions: {
        input: join(ROOT, 'web/src/main.mjs'),
        output: {
          entryFileNames: 'entry-[hash].mjs',
          chunkFileNames: 'chunk-[name]-[hash].mjs',
          assetFileNames: 'asset-[name]-[hash][extname]',
        },
      },
    },
  });
  const output = (Array.isArray(result) ? result[0] : result).output,
    dir = join(ROOT, 'site/ui');
  if (resolve(dir) !== join(ROOT, 'site', 'ui')) throw Error('Frontend target escaped');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const generated = {};
  const put = (path, bytes) => {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), bytes);
    generated[path] = createHash('sha256').update(bytes).digest('hex');
  };
  for (const f of output) put('site/ui/' + f.fileName, f.type === 'chunk' ? f.code : f.source);
  const entryChunk = output.find((f) => f.type === 'chunk' && f.isEntry),
    entry = entryChunk.fileName;
  const css = [...(entryChunk.viteMetadata?.importedCss || [])];
  const loader = `// Generated by scripts/build-frontend.mjs — edit web/src instead.\n${css.map((f) => `{const l=document.createElement('link');l.rel='stylesheet';l.href='/games/ui/${f}';document.head.append(l);}`).join('\n')}\nimport '/games/ui/${entry}';\n`;
  const entries = JSON.parse(readFileSync(join(ROOT, 'web/entries.json'), 'utf8'));
  for (const e of entries) {
    const folder = e.id === 'lobby' ? 'site' : `games/${e.id}/public`;
    const html = `<!doctype html>\n<html lang="zh-CN"><head>${e.head}</head><body><div id="vue-root"></div><script type="module" src="./app.mjs"></script></body></html>\n`;
    put(folder + '/' + e.page + '.html', html);
    put(folder + '/app.mjs', loader);
  }
  for (const id of ['pindou', 'goose', 'lianliankan', 'paopaotang'])
    put(`games/${id}/public/runtime.mjs`, readFileSync(join(ROOT, `web/src/legacy/${id}.mjs`)));
  const tankLicense = readFileSync(
    join(ROOT, 'games/tank/public/assets/battle-city-license.html'),
    'utf8',
  ).match(/<pre>([\s\S]*?)<\/pre>/)[1];
  const licenses =
    ['vue', 'vue-router', 'three']
      .map(
        (id) =>
          `<h2>${id}</h2><pre>${readFileSync(
            join(ROOT, 'node_modules', id, id === 'three' ? 'LICENSE' : 'LICENSE'),
            'utf8',
          )
            .replaceAll('&', '&amp;')
            .replaceAll('<', '&lt;')}</pre>`,
      )
      .join('') +
    '<h2>Battle City upstream engine (feichao93)</h2><pre>' +
    tankLicense +
    '</pre>';
  const licenseName =
    'licenses-' + createHash('sha256').update(licenses).digest('hex').slice(0, 12) + '.html';
  put(
    'site/ui/' + licenseName,
    '<!doctype html><meta charset="utf-8"><title>Runtime licenses</title>' + licenses,
  );
  for (const e of entries) {
    const folder = e.id === 'lobby' ? 'site' : `games/${e.id}/public`;
    put(folder + '/app.mjs', loader + `// Runtime licenses: /games/ui/${licenseName}\n`);
  }
  writeFileSync(
    join(ROOT, 'web/build-manifest.json'),
    JSON.stringify(
      {
        version: 1,
        framework: 'Vue 3 + Vue Router + Vite',
        sourceSha256: sourceHash(),
        entry,
        generated,
      },
      null,
      2,
    ) + '\n',
  );
  console.log(
    `Vue frontend: ${output.length} bundled files; ${entries.length} compatible entry pages.`,
  );
}
export function verifyFrontend() {
  const m = JSON.parse(readFileSync(join(ROOT, 'web/build-manifest.json'), 'utf8'));
  if (m.sourceSha256 !== sourceHash())
    throw Error('Vue sources changed; run npm run build:frontend');
  for (const [p, sha] of Object.entries(m.generated))
    if (
      createHash('sha256')
        .update(readFileSync(join(ROOT, p)))
        .digest('hex') !== sha
    )
      throw Error('Generated Vue artifact changed: ' + p);
  return m;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await buildFrontend();
